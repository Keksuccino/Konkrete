package de.keksuccino.konkrete.util.file.type;

/** Classifies a file's general media category. */
public enum FileMediaType {
    /** An image resource. */
    IMAGE,
    /** A video resource. */
    VIDEO,
    /** An audio resource. */
    AUDIO,
    /** A textual resource. */
    TEXT,
    /** A resource outside the known media categories. */
    OTHER
}
